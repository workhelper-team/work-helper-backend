package com.workhelper.domain.laborcase.dto;

import lombok.Getter;
import lombok.NoArgsConstructor;


// ============================================================
// 노동 사건 요청 DTO
// 노동 사건 생성 및 수정 API에서
// 클라이언트가 전달하는 요청 데이터를 담는 객체
// ============================================================
@Getter
@NoArgsConstructor
public class LaborCaseRequestDto {

    // ============================================================
    // 노동 사건 제목
    // 클라이언트가 사건의 제목을 입력하여 전달
    // ============================================================
    private String title;


    // ============================================================
    // 노동 사건 분류
    // 사건의 유형 또는 카테고리를 전달
    // ============================================================
    private String category;


    // ============================================================
    // 노동 사건 상태
    // API 요청에서 전달되는 사건 상태
    //
    // 상태값 자체는 설계서에 정의된 값을 사용하며
    // DTO에서 임의의 값을 지정하지 않음
    // ============================================================
    private String status;


    // ============================================================
    // 노동 사건 요약
    // 사건의 주요 내용을 요약하여 전달
    // ============================================================
    private String summary;

}